from __future__ import annotations

import io
import logging
import re
from datetime import UTC, datetime
from pathlib import Path
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen import canvas
from reportlab.platypus import KeepTogether, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

log = logging.getLogger("dealbridge.report")

DISCLAIMER = (
    "This document is an evidence-based preliminary assessment generated by DealBridge from the requirements provided by the buyer "
    "and from product knowledge available at the time of assessment. It is not a contractual guarantee, a certification, or a "
    "statement of compliance. Statuses marked Unknown or Needs validation have not been verified and require confirmation from the "
    "vendor. Statuses are assigned from cited source excerpts; retrieval similarity is not used as evidence. Buyer-specific "
    "compatibility must be validated by testing."
)
STATUS_TEXT = {
    "SUPPORTED": "Supported",
    "PARTIALLY_SUPPORTED": "Partially supported",
    "NEEDS_VALIDATION": "Needs validation",
    "NOT_SUPPORTED": "Not supported",
    "UNKNOWN": "Unknown",
}
STATUS_COLOR = {
    "SUPPORTED": "#15803d",
    "PARTIALLY_SUPPORTED": "#b45309",
    "NEEDS_VALIDATION": "#1e40af",
    "NOT_SUPPORTED": "#b91c1c",
    "UNKNOWN": "#475569",
}
PRIORITY_TEXT = {"CRITICAL": "Critical", "HIGH": "High", "MEDIUM": "Medium", "LOW": "Low", "NOT_SPECIFIED": "Not specified"}
ASSERTION_TEXT = {
    "NONE": "Comment",
    "CONFIRMS_SUPPORT": "Confirms support",
    "CONFIRMS_LIMITATION": "Confirms a limitation",
    "NEEDS_INFO_FROM_BUYER": "Needs information from the buyer",
}
FONT_DIR = Path(__file__).resolve().parent / "fonts"

_FONT = {"regular": "Helvetica", "bold": "Helvetica-Bold", "unicode": False}


def _register_fonts() -> None:
    if _FONT["unicode"]:
        return
    try:
        pdfmetrics.registerFont(TTFont("DejaVuSans", str(FONT_DIR / "DejaVuSans.ttf")))
        pdfmetrics.registerFont(TTFont("DejaVuSans-Bold", str(FONT_DIR / "DejaVuSans-Bold.ttf")))
        _FONT.update(regular="DejaVuSans", bold="DejaVuSans-Bold", unicode=True)
    except Exception as exc:
        log.warning(
            "DejaVu fonts unavailable; falling back to Helvetica (unsupported characters become '?')", extra={"error": type(exc).__name__}
        )


def _t(text) -> str:
    """Escape for Paragraph markup; without Unicode fonts, replace characters Helvetica cannot draw."""
    s = escape(str(text if text is not None else ""))
    if not _FONT["unicode"]:
        s = s.encode("latin-1", "replace").decode("latin-1")
    return s.replace("\n", "<br/>")


def _styles():
    ss = getSampleStyleSheet()
    r, b = _FONT["regular"], _FONT["bold"]
    return {
        "title": ParagraphStyle("title", parent=ss["Title"], fontName=b, fontSize=20, leading=24, alignment=TA_LEFT),
        "h1": ParagraphStyle(
            "h1",
            parent=ss["Heading1"],
            fontName=b,
            fontSize=14,
            leading=18,
            spaceBefore=10,
            spaceAfter=6,
            textColor=colors.HexColor("#312e81"),
        ),
        "h2": ParagraphStyle("h2", parent=ss["Heading2"], fontName=b, fontSize=11, leading=14, spaceBefore=8, spaceAfter=3),
        "body": ParagraphStyle("body", parent=ss["BodyText"], fontName=r, fontSize=9.5, leading=13),
        "small": ParagraphStyle("small", parent=ss["BodyText"], fontName=r, fontSize=8, leading=10, textColor=colors.HexColor("#475569")),
        "quote": ParagraphStyle(
            "quote", parent=ss["BodyText"], fontName=r, fontSize=8.5, leading=11, leftIndent=8, textColor=colors.HexColor("#334155")
        ),
        "cell": ParagraphStyle("cell", parent=ss["BodyText"], fontName=r, fontSize=8, leading=10),
        "cellb": ParagraphStyle("cellb", parent=ss["BodyText"], fontName=b, fontSize=8, leading=10),
    }


def _status(status: str, st) -> Paragraph:
    """Status as text plus a coloured chip (colour is an addition, never the only signal)."""
    return Paragraph(f'<font color="{STATUS_COLOR[status]}">&#9632;</font> <b>{_t(STATUS_TEXT[status])}</b>', st["cell"])


def _numbered_canvas(version_no: int):
    class NumberedCanvas(canvas.Canvas):
        def __init__(self, *args, **kwargs):
            super().__init__(*args, **kwargs)
            self._saved = []

        def showPage(self):  # noqa: N802 (ReportLab API)
            self._saved.append(dict(self.__dict__))
            self._startPage()

        def save(self):
            total = len(self._saved)
            for state in self._saved:
                self.__dict__.update(state)
                self.setFont(_FONT["regular"], 7.5)
                self.setFillColor(colors.HexColor("#64748b"))
                self.drawString(
                    18 * mm,
                    10 * mm,
                    f"DealBridge — preliminary evidence-based assessment — version {version_no} — page {self._pageNumber} of {total}",
                )
                super().showPage()
            super().save()

    return NumberedCanvas


def slug(text: str) -> str:
    return re.sub(r"[^A-Za-z0-9]+", "-", text).strip("-")[:60] or "assessment"


def filename(title: str, version_no: int, when: datetime | None = None) -> str:
    return f"DealBridge_Assessment_{slug(title)}_v{version_no}_{(when or datetime.now(UTC)).strftime('%Y%m%d')}.pdf"


def _list(items, st) -> list:
    if not items:
        return [Paragraph("None recorded.", st["small"])]
    return [Paragraph(f"• {_t(i)}", st["body"]) for i in items]


def build_report(results: dict, buyer_org: str | None, open_tickets: list[dict] | None) -> bytes:
    """results: the payload from build_results(). open_tickets: buyer's unresolved tickets (None when the seller downloads)."""
    _register_fonts()
    st = _styles()
    v = results["version"]
    s = results["summary"]
    reqs = results["requirements"]
    ctx = results["assessment"]["context"]
    story: list = []

    # 1. Cover
    story += [
        Spacer(1, 30 * mm),
        Paragraph(_t(results["assessment"]["title"]), st["title"]),
        Paragraph("Preliminary evidence-based product-fit assessment (IOMETE)", st["h2"]),
        Spacer(1, 6 * mm),
        Paragraph(f"Version {v['version_no']}", st["body"]),
        Paragraph(f"Generated {datetime.now(UTC).strftime('%Y-%m-%d %H:%M UTC')}", st["body"]),
        Paragraph(f"Assessment run {_t(str(v['analyzed_at'])[:16].replace('T', ' '))} UTC", st["body"]),
        Paragraph(f"Buyer organisation: {_t(buyer_org or ctx.get('organisation_name') or 'Not stated')}", st["body"]),
        Spacer(1, 10 * mm),
        Paragraph(_t(DISCLAIMER), st["small"]),
        PageBreak(),
    ]
    # 2. Executive summary, status counts, blockers
    counts = s.get("status_counts", {})
    story += [Paragraph("Executive summary", st["h1"]), Paragraph(_t(s.get("executive_summary", "")), st["body"]), Spacer(1, 3 * mm)]
    ct = Table(
        [[Paragraph("<b>Status</b>", st["cell"]), Paragraph("<b>Requirements</b>", st["cell"])]]
        + [[_status(k, st), Paragraph(str(counts.get(k, 0)), st["cell"])] for k in STATUS_TEXT],
        colWidths=[60 * mm, 30 * mm],
    )
    ct.setStyle(
        TableStyle(
            [("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")), ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2ff"))]
        )
    )
    story += [ct, Spacer(1, 3 * mm), Paragraph("Potential blockers", st["h2"])]
    story += _list([f"{b}: {next((r['text'] for r in reqs if r['display_id'] == b), '')}" for b in s.get("blockers", [])], st)
    # 3. Buyer context
    story += [Paragraph("Buyer context", st["h1"])]
    for label, key in (("Organisation", "organisation_name"), ("Industry", "industry"), ("Use case", "use_case")):
        story.append(Paragraph(f"<b>{label}:</b> {_t(ctx.get(key) or 'Not stated')}", st["body"]))
    # 4. Requirements overview
    story += [Paragraph("Requirements overview", st["h1"])]
    rows = [[Paragraph(f"<b>{h}</b>", st["cell"]) for h in ("ID", "Requirement", "Category", "Priority", "Status")]]
    for r in reqs:
        rows.append(
            [
                Paragraph(_t(r["display_id"]), st["cell"]),
                Paragraph(_t(r["text"]), st["cell"]),
                Paragraph(_t(r["category"].replace("_", " ").title()), st["cell"]),
                Paragraph(PRIORITY_TEXT[r["priority"]], st["cell"]),
                _status(r["status"], st),
            ]
        )
    ot = Table(rows, colWidths=[19 * mm, 75 * mm, 32 * mm, 20 * mm, 32 * mm], repeatRows=1)
    ot.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#cbd5e1")),
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef2ff")),
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ]
        )
    )
    story += [ot]
    # 5. Requirement details
    story += [PageBreak(), Paragraph("Requirement details", st["h1"])]
    for r in reqs:
        e = r.get("explanation") or {}
        block = [
            Paragraph(f"{_t(r['display_id'])} — {_t(r['text'])}", st["h2"]),
            Paragraph(f"Status: <b>{STATUS_TEXT[r['status']]}</b> · Priority: {PRIORITY_TEXT[r['priority']]}", st["body"]),
        ]
        for label, val in (
            ("What the requirement means", e.get("meaning")),
            ("What the evidence establishes", e.get("established")),
            ("What remains unverified", e.get("unverified")),
        ):
            if val:
                block.append(Paragraph(f"<b>{label}:</b> {_t(val)}", st["body"]))
        if r["status"] == "PARTIALLY_SUPPORTED":
            block.append(Paragraph(f"<b>Supported part:</b> {_t(r.get('supported_part'))}", st["body"]))
            block.append(Paragraph(f"<b>Not established:</b> {_t(r.get('unestablished_part'))}", st["body"]))
        story.append(KeepTogether(block))
        for ev in r.get("evidence", []):
            excerpt = ev["excerpt"] if len(ev["excerpt"]) <= 400 else ev["excerpt"][:397] + "..."
            story.append(
                Paragraph(
                    f"<b>Evidence [{_t(ev['label'])}]</b> {_t(ev['title'])} — {_t(ev.get('heading_path') or '')}<br/>{_t(ev.get('source_url') or ev.get('source_document') or '')}",
                    st["small"],
                )
            )
            story.append(Paragraph(f"“{_t(excerpt)}”", st["quote"]))
        if not r.get("evidence"):
            story.append(Paragraph("No cited excerpt establishes this requirement.", st["small"]))
        if r.get("missing_information"):
            story.append(Paragraph("<b>Missing information:</b> " + _t("; ".join(r["missing_information"])), st["body"]))
        if e.get("next_step"):
            story.append(Paragraph(f"<b>Next step:</b> {_t(e['next_step'])}", st["body"]))
        if r.get("has_conflict"):
            story.append(Paragraph(f"<b>Conflict:</b> {_t(r.get('conflict_description'))}", st["body"]))
        if r.get("guardrail_notes"):
            story.append(Paragraph("<b>Adjusted automatically:</b> " + _t(" ".join(r["guardrail_notes"])), st["small"]))
        for sr in r.get("seller_responses", []):
            story.append(
                Paragraph(
                    f"<b>Seller statement — not verified by product documentation</b> ({_t(sr['seller_name'])}, {_t(sr['seller_org'])}, {_t(str(sr['created_at'])[:16].replace('T', ' '))}): "
                    f"{_t(ASSERTION_TEXT.get(sr['assertion'], sr['assertion']))} — {_t(sr['body'])}",
                    st["small"],
                )
            )
        story.append(Spacer(1, 3 * mm))
    # 6-8. Assumptions, missing information, questions for the seller
    story += [Paragraph("Assumptions", st["h1"]), *_list(s.get("assumptions"), st)]
    story += [Paragraph("Missing information", st["h1"]), *_list(s.get("missing_information"), st)]
    story += [Paragraph("Questions for the seller", st["h1"]), *_list(s.get("questions_for_seller"), st)]
    # 9. Unresolved questions raised with the product team (buyer copy only)
    if open_tickets is not None:
        story += [Paragraph("Unresolved questions raised with the product team", st["h1"])]
        story += _list(
            [f"{t['display_id']}: {t['normalised_question']} ({t['status'].replace('_', ' ').lower()})" for t in open_tickets], st
        )
    # 10. Changes since the previous version
    changes = results.get("changes_since_previous")
    if v["version_no"] > 1:
        story += [Paragraph("Changes since the previous version", st["h1"])]
        story += _list(
            [
                f"{c['display_id']}: {c['change'].replace('_', ' ').lower()}"
                + (
                    f" ({STATUS_TEXT.get(c['previous_status'], '-')} → {STATUS_TEXT.get(c['new_status'], '-')})"
                    if c["change"] == "STATUS_CHANGED"
                    else ""
                )
                for c in (changes or [])
            ],
            st,
        )
    # 11. Next steps, 12. Limitations
    story += [Paragraph("Recommended next steps", st["h1"]), *_list(s.get("next_steps"), st)]
    story += [Paragraph("Limitations and disclaimer", st["h1"]), Paragraph(_t(DISCLAIMER), st["body"])]

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=16 * mm,
        bottomMargin=18 * mm,
        title=f"DealBridge assessment — {results['assessment']['title']}",
        author="DealBridge",
    )
    doc.build(story, canvasmaker=_numbered_canvas(v["version_no"]))
    return buf.getvalue()
